import type { AnnotationPlugin, ReadonlyDeclaration as Declaration } from '#core';
import type { AnnotationDiagnostic, FactEvidence, Reference } from '#core/wire';
import { canonicalJSON } from '#core/wire';
import type { SyntaxNode, TypeScriptView } from '#typescript';
import { canonicalApi, descriptor } from './vocabulary.js';
import { analyzeCore } from './core-analysis.js';
import { familySafety } from './family-safety.js';
export { fstReturnContracts } from './core-rules.js';
export type { FstSolidRole, FstSolidProperty, FstSolidRelation } from './vocabulary.js';
import type { FstSolidRole, FstSolidProperty, FstSolidRelation } from './vocabulary.js';

type Family = 'state' | 'form' | 'scope' | 'item-scope';
interface ClassInfo { declaration: Declaration; node: SyntaxNode; family: Family; base?: ClassInfo }
interface Instance { classInfo: ClassInfo; reference: Reference; raw: boolean; origin: SyntaxNode }
interface FieldInfo { reference: Reference; creation: SyntaxNode; origin?: SyntaxNode; unprovenMethod?: boolean }
const families: Readonly<Record<string, Family>> = { State: 'state', Form: 'form', Scope: 'scope', ItemScope: 'item-scope' };
const lifetime: Readonly<Record<Family, readonly string[]>> = {
  state: ['new', 'newScoped', 'use', 'useOrNull', 'useOrNewScoped', 'useGlobal', 'asScoped'],
  form: ['new', 'newScoped', 'use', 'useOrNewScoped', 'useGlobal', 'asScoped'],
  scope: ['newScoped', 'use', 'useOrNewScoped'],
  'item-scope': ['newScoped', 'use'],
};
const lifetimeNames = new Set(Object.values(lifetime).flat());
const functions = new Set(['arrow_function', 'function_expression', 'function_declaration', 'generator_function', 'generator_function_declaration']);

/** Reviewed file-local rules only. Digests are generated by the consumer's build. */
export function createFstSolidPlugin(digests: { implementationDigest: string; configurationDigest: string }): AnnotationPlugin<TypeScriptView> {
  return {
    descriptor: descriptor(digests),
    analyze({ view, budget }, emitter) {
      if (view.state === 'truncated' || view.state === 'unsupported' || view.state === 'failed') return { state: view.state };
      // No per-declaration projections or receiver analysis for unrelated files.
      if (!view.nodes.some((node) => node.type === 'import_statement' && node.fields.source && view.moduleIdentity(node.fields.source)?.startsWith('@fst/components-fst-solid/'))) return { state: 'not-applicable' };
      const diagnostics: AnnotationDiagnostic[] = [];
      let matched = false, partial = false;
      const diagnose = (code: string, message: string, node: SyntaxNode) => {
        partial = true;
        if (diagnostics.length < 16 && !diagnostics.some((item) => item.code === code)) diagnostics.push({ code, message, span: view.span(node) });
      };
      const evidence = (node: SyntaxNode, ruleId: string, basis: FactEvidence['basis'] = 'import-bound'): Omit<FactEvidence, 'pluginId'> => ({ ruleId, basis, span: view.span(node) });
      const wireSize = (value: unknown) => {
        let bytes = 0;
        for (const point of canonicalJSON(value)) { const code = point.codePointAt(0)!; bytes += code < 128 ? 1 : code < 2048 ? 2 : code < 65536 ? 3 : 4; }
        return bytes;
      };
      const role = (subject: Declaration, term: FstSolidRole, node: SyntaxNode, rule: string) => { matched = true; emitter.role(subject.key, term, evidence(node, rule)); };
      const property = (subject: Declaration, term: FstSolidProperty, value: string, node: SyntaxNode, rule: string, resolution: 'literal' | 'constant' = 'literal') => {
        matched = true; emitter.property(subject.key, term, resolution, { kind: 'string', value }, evidence(node, rule));
      };
      const relation = (subject: Declaration, term: FstSolidRelation, target: Reference, node: SyntaxNode, rule: string, basis: FactEvidence['basis'] = 'import-bound') => {
        budget.step();
        if (wireSize(target) > view.limits.maxValueBytes) { diagnose('fst-solid.reference-limit', 'Source reference exceeds the bounded wire value size.', node); return; }
        matched = true; emitter.relation(subject.key, term, target, evidence(node, rule, basis));
      };
      const api = (input: SyntaxNode | undefined, space: 'value' | 'type' = 'value') => {
        if (!input) return undefined;
        const origin = view.resolve(input, space);
        return origin.kind === 'import' && !origin.member ? canonicalApi(origin.module, origin.name) : undefined;
      };
      const argumentsOf = (node: SyntaxNode) => node.fields.arguments?.children.filter((child) => child.type !== 'comment') ?? [];
      const member = (node: SyntaxNode) => {
        const value = view.unwrap(node);
        if (value.type !== 'member_expression' || value.tokens.includes('?.')) return undefined;
        const object = value.fields.object, property = value.fields.property;
        return object && property ? { object, name: view.name(property) ?? view.text(property) } : undefined;
      };
      const declarationMap = new Map(view.declarations.map((declaration) => [declaration.key, declaration]));
      const classes = new Map<string, ClassInfo>();
      const classify = (declaration: Declaration, seen = new Set<string>()): ClassInfo | undefined => {
        budget.step(); budget.depth(seen.size);
        if (classes.has(declaration.key)) return classes.get(declaration.key);
        if (declaration.kind !== 'class' || seen.has(declaration.key) || seen.size >= 24) return undefined;
        seen.add(declaration.key);
        const node = view.declarationNode(declaration.key);
        const heritage = node?.children.find((child) => child.type === 'class_heritage');
        const extension = heritage?.children.find((child) => child.type === 'extends_clause');
        const base = extension?.fields.value;
        if (!node || !base) return undefined;
        const name = api(base), resolved = view.resolve(base);
        const parent = resolved.kind === 'declaration' && declarationMap.get(resolved.key);
        const inherited = parent ? classify(parent, seen) : undefined;
        const family = name && Object.hasOwn(families, name) ? families[name] : inherited?.family;
        if (!family) return undefined;
        const info: ClassInfo = { declaration, node, family, ...(inherited ? { base: inherited } : {}) };
        classes.set(declaration.key, info);
        role(declaration, `fst-solid.${family}`, base, inherited ? 'local-base-family' : 'base-family');
        relation(declaration, 'fst-solid.extends', resolved, base, 'base-family');
        for (const type of extension?.fields.type_arguments?.children ?? []) relation(declaration, 'fst-solid.type-argument', view.reference(type, 'type'), type, 'base-types', 'syntax');
        return info;
      };
      for (const declaration of view.declarations) {
        if (declaration.kind !== 'class' || classify(declaration)) continue;
        const node = view.declarationNode(declaration.key);
        const base = node?.children.find((child) => child.type === 'class_heritage')?.children.find((child) => child.type === 'extends_clause')?.fields.value;
        if (!base) continue;
        const resolved = view.resolve(base);
        if (resolved.kind === 'import' || resolved.kind === 'declaration') diagnose('fst-solid.unresolved-base', 'Base-family heritage is not proven through a bounded local canonical inheritance chain.', base);
      }
      const classOf = (node: SyntaxNode): ClassInfo | undefined => {
        const reference = view.resolve(node);
        return reference.kind === 'declaration' ? classes.get(reference.key) : undefined;
      };
      const overrides = (info: ClassInfo, name: string, isStatic: boolean) => {
        for (let current: ClassInfo | undefined = info; current; current = current.base) {
          budget.step();
          if (current.node.fields.body?.children.some((child) => {
            budget.step();
            if (isStatic && child.type === 'class_static_block') return true;
            const memberName = view.declarationAt(child)?.name ?? (child.fields.name && view.name(child.fields.name));
            return child.tokens.includes('static') === isStatic && (child.fields.name?.type === 'computed_property_name' || memberName === name);
          })) return true;
        }
        return false;
      };
      const safety = familySafety(view, budget, classes, lifetimeNames);
      const inheritedMethod = (info: ClassInfo, name: string) => !overrides(info, name, false) && !safety.changed(info, name) &&
        !safety.changed(info, 'buildMember') && !safety.changed(info, 'build') && !overrides(info, 'buildMember', false) && !overrides(info, 'build', false);
      const staticCall = (node: SyntaxNode) => {
        if (node.type !== 'call_expression' || !node.fields.function) return undefined;
        const access = member(node.fields.function);
        const info = access && classOf(access.object);
        if (!access || !info || !lifetime[info.family].includes(access.name)) return undefined;
        if (overrides(info, access.name, true) || safety.staticChanged(info, access.name)) {
          diagnose('fst-solid.static-override', 'A local override, mutation or escape prevents an inherited lifetime API claim.', node); return undefined;
        }
        return { info, name: access.name, object: access.object };
      };
      const instance = (input: SyntaxNode, seen = new Set<string>(), reportThis = false): Instance | undefined => {
        budget.step(); budget.depth(seen.size);
        if (seen.size >= 24) return undefined;
        const node = view.unwrap(input), ref = view.reference(node);
        if (node.type === 'this') {
          let cursor = view.parent(node);
          while (cursor) {
            budget.step();
            if ((functions.has(cursor.type) && cursor.type !== 'arrow_function') || cursor.type === 'class_static_block' || cursor.type === 'computed_property_name') break;
            // Arrows inherit this, but only the nearest instance member establishes it.
            if (cursor.type === 'method_definition' || cursor.type === 'public_field_definition') {
              const body = view.parent(cursor);
              if (cursor.tokens.includes('static') || body?.type !== 'class_body') break;
              const owner = view.parent(body), decl = owner && view.declarationAt(owner), info = decl && classes.get(decl.key);
              if (info) return { classInfo: info, reference: ref, raw: true, origin: cursor };
              break;
            }
            if (['class_declaration', 'abstract_class_declaration', 'class'].includes(cursor.type)) break;
            cursor = view.parent(cursor);
          }
          if (reportThis) diagnose('fst-solid.unresolved-this', 'This receiver is not proven to be a local FST instance.', node);
          return undefined;
        }
        const direct = staticCall(node);
        if (direct) {
          if (direct.name === 'asScoped') {
            const input = argumentsOf(node)[0];
            const original = input && input.type !== 'spread_element' ? instance(input, seen, reportThis) : undefined;
            return original?.classInfo.declaration.key === direct.info.declaration.key ? { ...original, reference: ref } : undefined;
          }
          return { classInfo: direct.info, reference: ref, raw: !['new', 'newScoped'].includes(direct.name), origin: node };
        }
        if (node.type === 'new_expression' && node.fields.constructor) {
          const info = classOf(node.fields.constructor);
          if (info) return { classInfo: info, reference: ref, raw: true, origin: node };
        }
        const binding = view.binding(node);
        if (binding?.kind === 'const' && binding.available && binding.stable && binding.initializer && binding.declaration && !seen.has(binding.declaration)) {
          seen.add(binding.declaration);
          const target = instance(binding.initializer, seen, reportThis);
          if (target) return { ...target, reference: ref };
        }
        return undefined;
      };
      const field = (input: SyntaxNode, seen = new Set<string>()): FieldInfo | undefined => {
        budget.step(); budget.depth(seen.size);
        if (seen.size >= 24) return undefined;
        const node = view.unwrap(input), reference = view.reference(node);
        if (node.type === 'call_expression' && node.fields.function) {
          if (api(node.fields.function) === 'field') return { reference, creation: node };
          const access = member(node.fields.function);
          if (access?.name === 'field') {
            const value = instance(access.object, new Set(), true);
            if (value?.classInfo.family === 'form' && inheritedMethod(value.classInfo, 'field')) return { reference, creation: node, origin: access.object };
          }
          if (access && ['onChange', 'onSet', 'map'].includes(access.name)) {
            const original = field(access.object, seen);
            if (original) {
              budget.step(512);
              return view.project(node.fields.function) ? original : { ...original, unprovenMethod: true };
            }
          }
        }
        const binding = view.binding(node);
        if (binding?.kind === 'const' && binding.available && binding.stable && binding.initializer && binding.declaration && !seen.has(binding.declaration)) {
          seen.add(binding.declaration);
          const result = field(binding.initializer, seen);
          if (result) return { ...result, reference };
        }
        return undefined;
      };
      const assigned = (call: SyntaxNode): Declaration | undefined => {
        let cursor = call;
        for (let i = 0; i < 64; i++) {
          budget.step();
          const decl = view.declarationAt(cursor);
          if (decl) return decl;
          const parent = view.parent(cursor);
          if (!parent) return undefined;
          if (['parenthesized_expression', 'as_expression', 'satisfies_expression', 'type_assertion', 'non_null_expression', 'instantiation_expression'].includes(parent.type)) { cursor = parent; continue; }
          if (['variable_declarator', 'public_field_definition'].includes(parent.type) && parent.fields.value?.startIndex === cursor.startIndex) return view.declarationAt(parent);
          return undefined;
        }
        return undefined;
      };
      const subject = (node: SyntaxNode, fallback?: Reference) => view.owner(node) ?? (fallback?.kind === 'declaration' ? declarationMap.get(fallback.key) : undefined);
      const safeString = (value: string) => {
        if (/[\x00-\x08\x0b\x0c\x0e-\x1f\x7f]/.test(value)) return false;
        for (const point of value) { const code = point.codePointAt(0)!; if (code >= 0xd800 && code <= 0xdfff) return false; }
        return wireSize({ kind: 'string', value }) <= view.limits.maxValueBytes;
      };
      const stringOption = (owner: Declaration, node: SyntaxNode | undefined, key: string, term: FstSolidProperty, anchor: SyntaxNode) => {
        if (!node) { emitter.property(owner.key, term, 'absent', undefined, evidence(anchor, 'component-options')); return; }
        budget.step(512);
        const value = view.constantProperty(node, key);
        if (value.known && typeof value.value === 'string' && safeString(value.value)) property(owner, term, value.value, node, 'component-options', value.resolution);
        else if (!value.known && value.reason === 'absent') emitter.property(owner.key, term, 'absent', undefined, evidence(node, 'component-options'));
        else { emitter.property(owner.key, term, 'expression', undefined, evidence(node, 'component-options')); diagnose('fst-solid.dynamic-options', 'Component metadata is not a proven bounded string constant.', node); }
      };
      const changeArguments = (owner: Declaration, dependencies: SyntaxNode, callback: SyntaxNode, mode = 'onChange') => {
        const inputs = dependencies.children.filter((child) => child.type !== 'comment');
        const punctuation = (start: number, end: number) => view.source.slice(start, end).replace(/\/\*[\s\S]*?\*\/|\/\/[^\r\n]*/g, '').trim();
        if (!inputs.length || inputs.length > (mode === 'onChange' ? 4 : 3) || (mode === 'resolveChildrenOnChange' && inputs.length < 2) || inputs.some((input, index) =>
          input.type === 'spread_element' || punctuation(index ? inputs[index - 1]!.endIndex : dependencies.startIndex + 1, input.startIndex) !== (index ? ',' : '')) ||
          !['', ','].includes(punctuation(inputs.at(-1)!.endIndex, dependencies.endIndex - 1))) {
          diagnose('fst-solid.dynamic-dependencies', 'Callback projections require the supported explicit dependency arity without holes or spreads.', dependencies);
          return;
        }
        let fn = view.unwrap(callback);
        const seen = new Set<SyntaxNode>();
        while (!functions.has(fn.type) && seen.size < 24 && !seen.has(fn)) {
          budget.step();
          seen.add(fn);
          const binding = view.binding(fn);
          if (!binding?.available || !binding.stable) return;
          const next = binding.initializer ?? (binding.kind === 'function' && binding.declaration ? view.declarationNode(binding.declaration) : undefined);
          if (!next) return;
          fn = view.unwrap(next);
        }
        if (!functions.has(fn.type)) return;
        const parameters = fn.fields.parameters ?? fn.fields.parameter;
        const parameter = parameters?.type === 'formal_parameters' ? parameters.children.find((child) => child.type !== 'comment') : parameters;
        if (!parameter) return;
        const projected = view.patternProjections(parameter);
        if (!projected.complete || projected.projections.some(({ path }) => path.length > 1 || (path.length === 1 && (typeof path[0] !== 'number' || path[0] >= inputs.length)))) {
          diagnose('fst-solid.callback-pattern', 'Only bounded positional callback bindings are projected to change snapshots.', parameter);
          return;
        }
        for (const { node, path } of projected.projections) {
          budget.step();
          if (path.length !== 1 || typeof path[0] !== 'number') continue;
          const name = view.name(node), dependency = inputs[path[0]];
          if (!name || !dependency || !safeString(name)) continue;
          const bindingOwner = view.owner(node) ?? owner;
          property(bindingOwner, mode === 'resolveChildrenOnChange' && path[0] === 0 ? 'fst-solid.children-change-argument' : 'fst-solid.change-argument', name, node, 'change-argument');
          relation(bindingOwner, 'fst-solid.change-argument-source', view.reference(dependency), node, 'change-argument');
        }
      };
      for (const declaration of view.declarations) {
        budget.step();
        const node = view.declarationNode(declaration.key);
        if (!node) continue;
        if (declaration.kind === 'method' && declaration.owner) {
          const info = classes.get(declaration.owner);
          if (info && !node.tokens.some(token => ['static', 'get', 'set'].includes(token))) {
            const name = declaration.name;
            const hook = info.family === 'form' && ['init', 'save', 'submit', 'validate', 'errors'].includes(name ?? '') ? `form.${name}` : ['state', 'scope', 'item-scope'].includes(info.family) && name === 'initLoad' ? `${info.family}.initLoad` : undefined;
            if (hook) { role(declaration, 'fst-solid.lifecycle-hook', node, 'method-hook'); property(declaration, 'fst-solid.hook-kind', hook, node, 'method-hook'); }
            if (hook && ['scope', 'item-scope'].includes(info.family)) property(declaration, 'fst-solid.api-policy', 'initialization-enabled effect requests initLoad through webview readiness; completion flags set in finally; invocation, success and scheduling unproven', node, 'scope-initialization');
            else if (info.family === 'state' && name === 'init') property(declaration, 'fst-solid.hook-kind', 'state.init-configuration-override', node, 'state-configuration');
          }
        }
        const value = node.fields.value && view.unwrap(node.fields.value);
        if (value) {
          const handle = field(value);
          if (handle) {
            if (handle.unprovenMethod) property(declaration, 'fst-solid.api-policy', 'authored Field source lineage only; fluent method and returned callable identity unproven', value, 'field-creation');
            else role(declaration, 'fst-solid.field', value, 'field-creation');
            if (handle.origin) {
              relation(declaration, 'fst-solid.form-origin', view.reference(handle.origin), value, 'form-field');
              const path = argumentsOf(handle.creation)[0];
              if (path) relation(declaration, 'fst-solid.field-path-expression', view.reference(path), value, 'form-field', 'syntax');
              budget.step(512);
              const literal = path && view.constant(path);
              if (literal?.known && typeof literal.value === 'string' && safeString(literal.value)) property(declaration, 'fst-solid.field-path', literal.value, value, 'form-field', path!.startIndex >= value.startIndex && path!.endIndex <= value.endIndex ? literal.resolution : 'constant');
              else { emitter.property(declaration.key, 'fst-solid.field-path', 'expression', undefined, evidence(value, 'form-field')); diagnose('fst-solid.dynamic-field-path', 'Field path remains an expression, not a resolved TypeScript property.', value); }
            }
            for (const type of handle.creation.fields.type_arguments?.children ?? []) relation(declaration, 'fst-solid.value-type', view.reference(type, 'type'), value, 'field-value-type', 'syntax');
          }
        }
      }
      for (const node of view.nodes) {
        budget.step();
        if (node.type === 'generic_type' || node.type === 'type_identifier') {
          const name = node.type === 'generic_type' ? node.fields.name : node;
          const typeApi = api(name, 'type');
          if (typeApi === 'Field' || typeApi === 'InputField' || typeApi === 'FormField') {
            if (node.type === 'type_identifier' && view.parent(node)?.type === 'generic_type') continue;
            const owner = subject(node);
            if (owner) {
              relation(owner, 'fst-solid.field-type', view.resolve(name!, 'type'), node, 'field-type', 'syntax');
              for (const type of node.fields.type_arguments?.children ?? []) relation(owner, 'fst-solid.value-type', view.reference(type, 'type'), type, 'field-type', 'syntax');
            }
          }
        }
        if (node.type === 'new_expression' && node.fields.constructor) {
          const info = classOf(node.fields.constructor), owner = subject(node);
          if (info && owner) { property(owner, 'fst-solid.instance-kind', 'raw-constructor', node, 'raw-construction'); relation(owner, 'fst-solid.lifetime-target', { kind: 'declaration', key: info.declaration.key }, node, 'raw-construction'); }
          else if (['Field', 'InputField', 'FormField'].includes(api(node.fields.constructor, 'type') ?? '')) diagnose('fst-solid.type-construction', 'Field type references are not runtime constructors.', node);
          continue;
        }
        if (node.type !== 'call_expression' || !node.fields.function) continue;
        const fn = node.fields.function, args = argumentsOf(node), called = api(fn), access = member(fn);
        if (called === 'component' || called === 'componentWithChildren') {
          const owner = assigned(node);
          if (!args[0] || args.some((arg) => arg.type === 'spread_element')) { diagnose('fst-solid.component-shape', 'Component constructions require an explicit renderer without positional spreads.', node); continue; }
          if (!owner) {
            let value = node, parent = view.parent(value);
            while (parent && ['parenthesized_expression', 'as_expression', 'satisfies_expression', 'type_assertion', 'non_null_expression'].includes(parent.type)) { budget.step(); value = parent; parent = view.parent(value); }
            let factory = parent?.type === 'arrow_function' && parent.fields.body === value ? parent : undefined;
            if (parent?.type === 'return_statement') {
              for (let at = view.parent(parent); at; at = view.parent(at)) {
                budget.step();
                if (functions.has(at.type) || at.type === 'method_definition') { factory = at; break; }
              }
            }
            const factoryOwner = factory && !factory.tokens.includes('async') && !factory.type.includes('generator') && !factory.tokens.includes('*') ? view.declarationAt(factory) ?? assigned(factory) : undefined;
            if (!factoryOwner) { diagnose('fst-solid.component-shape', 'Construction is not a directly assigned component or a declared synchronous factory return.', node); continue; }
            role(factoryOwner, 'fst-solid.component-factory', node, 'returned-component-construction');
            relation(factoryOwner, 'fst-solid.returns-component', view.reference(node), node, 'returned-component-construction');
            relation(factoryOwner, 'fst-solid.factory', view.resolve(fn), fn, 'returned-component-construction');
            relation(factoryOwner, 'fst-solid.returned-renderer', view.reference(args[0]), args[0], 'returned-component-construction');
            if (args[1]) relation(factoryOwner, 'fst-solid.returned-options', view.reference(args[1]), args[1], 'returned-component-construction', 'syntax');
            property(factoryOwner, 'fst-solid.component-return', 'authored construction; metadata evaluated per invocation; other returns and callers not inferred', node, 'returned-component-construction');
            continue;
          }
          role(owner, 'fst-solid.component', node, 'component-factory');
          relation(owner, 'fst-solid.factory', view.resolve(fn), fn, 'component-factory');
          relation(owner, 'fst-solid.implemented-by', view.reference(args[0]), args[0], 'component-renderer');
          for (const type of node.fields.type_arguments?.children ?? []) relation(owner, 'fst-solid.props-type', view.reference(type, 'type'), type, 'component-props', 'syntax');
          if (!node.fields.type_arguments) {
            const ref = view.reference(args[0]);
            const declared = ref.kind === 'declaration' ? view.declarationNode(ref.key) : undefined;
            const renderer = view.unwrap(declared?.fields.value ?? declared ?? args[0]);
            const parameter = renderer.fields.parameters?.children[0] ?? renderer.fields.parameter;
            const type = parameter?.fields.type?.children[0];
            if (type) relation(owner, 'fst-solid.props-type', view.reference(type, 'type'), args[0], 'renderer-props', 'syntax');
          }
          stringOption(owner, args[1], 'name', 'fst-solid.name', node);
          stringOption(owner, args[1], 'designName', 'fst-solid.design-name', node);
          stringOption(owner, args[1], 'designConcept', 'fst-solid.design-concept', node);
          continue;
        }
        const inherited = staticCall(node);
        if (inherited) {
          const owner = subject(node, { kind: 'declaration', key: inherited.info.declaration.key });
          if (owner) {
            const operation: Record<string, string> = { new: 'create-standalone', newScoped: 'create-scoped', use: 'require-existing', useOrNull: 'optional-existing', useOrNewScoped: 'reuse-or-create-scoped', useGlobal: 'reuse-or-create-global', asScoped: 'provide-existing' };
            property(owner, 'fst-solid.lifetime-operation', operation[inherited.name]!, node, 'lifetime-call');
            relation(owner, 'fst-solid.lifetime-target', { kind: 'declaration', key: inherited.info.declaration.key }, node, 'lifetime-call');
            if (['use', 'useOrNull', 'useOrNewScoped'].includes(inherited.name)) property(owner, 'fst-solid.lookup-policy', ['state', 'form'].includes(inherited.info.family) ? 'scoped-with-global-fallback' : 'scoped-only', node, 'lifetime-call');
          }
        } else if (access && lifetimeNames.has(access.name) && api(access.object) !== 'List') {
          const origin = view.resolve(access.object), declared = view.reference(access.object);
          if (origin.kind === 'import' || (declared.kind === 'declaration' && classes.has(declared.key))) diagnose('fst-solid.unresolved-lifetime', 'The receiver or family API is not a proven inherited lifetime operation.', node);
        }
        const owner = subject(node);
        if (called === 'field' && owner) {
          property(owner, 'fst-solid.field-operation', 'construct-standalone', node, 'field-creation');
          relation(owner, 'fst-solid.factory', view.resolve(fn), fn, 'field-creation');
        }
        if (access?.name === 'field' && owner) {
          const handle = field(node);
          if (handle?.origin) {
            property(owner, 'fst-solid.field-operation', 'access-form-field', node, 'form-field');
            relation(owner, 'fst-solid.form-origin', view.reference(handle.origin), node, 'form-field');
            if (args[0]) relation(owner, 'fst-solid.field-path-expression', view.reference(args[0]), node, 'form-field', 'syntax');
          }
        }
        if (access?.name === 'form' && instance(access.object)?.classInfo.family === 'form') diagnose('fst-solid.subform-expression', 'Subform traversal remains an unresolved form expression in this file-local slice.', node);
        if (called === 'useFieldBinding') {
          if (!owner || !args[0]) { diagnose('fst-solid.unattached-registration', 'A binding call without a containing declaration is not represented.', node); continue; }
          const assignedOwner = assigned(node) ?? owner;
          role(assignedOwner, 'fst-solid.field-binding', node, 'field-binding');
          property(assignedOwner, 'fst-solid.ownership', 'borrowed-no-disposal', node, 'field-binding');
          relation(assignedOwner, 'fst-solid.borrows', view.reference(args[0]), args[0], 'field-binding');
        }
        if (called && ['onChange', 'onChangeDelayed', 'resolveChildrenOnChange', 'onCleanup', 'onComponentCleanup', 'onMount'].includes(called)) {
          if (!owner) { diagnose('fst-solid.unattached-registration', 'A registration without a containing declaration is not represented.', node); continue; }
          role(owner, 'fst-solid.registration', node, 'registration');
          const contract = called === 'onCleanup' ? 'solid.content-or-effect-cleanup' : called === 'onComponentCleanup' ? 'fst.wrapper-cleanup' : called === 'onMount' ? 'solid.content-mount' : called === 'onChangeDelayed' ? 'explicit-delayed-dependency-watch' : called === 'resolveChildrenOnChange' ? 'explicit-children-dependency-watch' : 'explicit-dependency-watch';
          property(owner, 'fst-solid.registration-kind', contract, node, 'registration');
          const watch = ['onChange', 'onChangeDelayed', 'resolveChildrenOnChange'].includes(called);
          const callback = args[called === 'onChangeDelayed' ? 2 : watch ? 1 : 0];
          if (callback) relation(owner, 'fst-solid.callback', view.reference(callback), callback, 'registration');
          if (watch) {
            const dependencies = args[called === 'onChangeDelayed' ? 1 : 0];
            const deps = dependencies && view.unwrap(dependencies);
            if (deps?.type === 'array' && !deps.children.some((child) => child.type === 'spread_element')) {
              for (const dep of deps.children.filter((child) => child.type !== 'comment')) relation(owner, 'fst-solid.observes', view.reference(dep), dep, 'explicit-dependencies', 'syntax');
              if (callback) changeArguments(owner, deps, callback, called);
            }
            else if (deps) { relation(owner, 'fst-solid.observes', view.reference(deps), deps, 'explicit-dependencies', 'syntax'); diagnose('fst-solid.dynamic-dependencies', 'Only explicit dependency arrays are enumerated; reactive dependency discovery is not performed.', deps); }
          }
        }
        if (access && ['onChange', 'onSet'].includes(access.name)) {
          const handle = field(access.object), target = subject(node, handle?.reference);
          if (handle && target) {
            role(target, 'fst-solid.registration', node, 'field-observer');
            property(target, 'fst-solid.observation-phase', access.name === 'onChange' ? 'pre-commit' : 'post-commit', node, 'field-observer');
            relation(target, 'fst-solid.field-target', handle.reference, access.object, 'field-observer');
            if (args[0]) relation(target, 'fst-solid.callback', view.reference(args[0]), args[0], 'field-observer');
          }
        }
        if (access?.name === 'init' && owner) {
          const receiver = instance(access.object);
            if (receiver?.classInfo.family === 'state' && inheritedMethod(receiver.classInfo, 'init')) {
            property(owner, 'fst-solid.registration-kind', 'state.init-configuration', node, 'state-configuration');
            if (args[0]) relation(owner, 'fst-solid.callback', view.reference(args[0]), args[0], 'state-configuration');
          }
        }
        const handle = field(fn), target = subject(node, handle?.reference);
        if (handle && target) {
          if (handle.unprovenMethod) {
            diagnose('fst-solid.unknown-field-value', 'Fluent Field invocation requires a proven, unescaped method result.', node);
            continue;
          }
          if (args.some(arg => arg.type === 'spread_element') || node.tokens.includes('?.') || node.children.some(child => child.type === 'optional_chain')) {
            diagnose('fst-solid.unknown-field-value', 'Field dispatch requires an unconditional call with explicit argument positions.', node);
            continue;
          }
          budget.step(512);
          const value = args[0] && view.constant(args[0]);
          const read = args.length === 0 || (value?.known && value.value === undefined);
          const write = (value?.known && value.value !== undefined) || (args[0] && functions.has(view.unwrap(args[0]).type));
          if (read || write) property(target, 'fst-solid.field-operation', read ? 'read' : 'write-request', node, 'field-invocation');
          else if (args[0]) {
            property(target, 'fst-solid.field-operation', 'conditional-read-or-write-request', node, 'field-invocation');
            property(target, 'fst-solid.field-dispatch', 'argument[0] === undefined: read; otherwise: write request (function inputs are updaters); branch, value, completion and disposal state unproven', node, 'field-invocation');
            relation(target, 'fst-solid.field-argument', { kind: 'expression', text: view.text(args[0]), span: view.span(args[0]) }, node, 'field-invocation');
            if (args[1]) relation(target, 'fst-solid.field-write-options', { kind: 'expression', text: view.text(args[1]), span: view.span(args[1]) }, node, 'field-invocation');
          }
          relation(target, 'fst-solid.field-target', handle.reference, fn, 'field-invocation');
        }
      }
      analyzeCore({ view, budget, hasFamilies: classes.size > 0, role, property, relation, diagnose, safeString, assigned,
        family(input, method) {
          if (!classes.size) return undefined;
          const value = instance(input);
          if (!value || method && !inheritedMethod(value.classInfo, method)) return undefined;
          return { kind: value.classInfo.family, raw: value.raw, origin: value.origin };
        },
        command(input, name) {
          if (!classes.size || name.startsWith('_') || name.startsWith('$') || name.startsWith('#') || ['constructor', 'init', 'build', 'buildMember', 'onChange'].includes(name)) return false;
          const value = instance(input);
          return !!value && !value.raw && value.classInfo.family === 'state' && !safety.customProxy(value.classInfo) && !safety.changed(value.classInfo, name) && !!value.classInfo.node.fields.body?.children.some((child) => child.type === 'method_definition' && !child.tokens.some((token) => ['static', 'get', 'set'].includes(token)) && child.fields.name && view.name(child.fields.name) === name);
        },
      });
      return { state: partial ? 'partial' : matched ? 'complete' : 'not-applicable', diagnostics };
    },
  };
}
